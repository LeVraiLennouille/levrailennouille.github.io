document.addEventListener("DOMContentLoaded", function () {
    var grid = document.querySelector("[data-reals-grid]");
    if (!grid) return;

    var sorted = REALS.filter(function (p) {
        return !p.comingSoon;
    }).sort(function (a, b) {
        return new Date(b.date) - new Date(a.date);
    });

    grid.innerHTML = sorted.map(renderProjectCard).join("");

    function renderProjectCard(p) {
        var attrs = p.comingSoon ? ' id="ComingSoonLink"' : "";
        return "" +
            '<a href="' + p.url + '" class="ProjectCard"' + attrs + '>' +
                '<div class="ProjectImage">' +
                    '<img src="' + p.image + '" alt="' + p.imageAlt + '">' +
                    '<div class="ProjectOverlay"><p>' + p.label + "</p></div>" +
                "</div>" +
            "</a>";
    }
});

(function () {
    var SIMILAR_COUNT = 3;
    var LATEST_COUNT = 2;
    var filled = false;

    function fillRelated(section) {
        var currentId = getCurrentProjectId();
        var current = findProject(currentId);
        if (!current) return false;

        var others = REALS.filter(function (p) { return p.id !== current.id && !p.comingSoon; });

        var ranked = others
            .map(function (p) { return { reals: p, score: similarityScore(current, p) }; })
            .sort(function (a, b) {
                if (b.score !== a.score) return b.score - a.score;
                return new Date(b.reals.date) - new Date(a.reals.date);
            });

        var similar = ranked.slice(0, SIMILAR_COUNT).map(function (r) { return r.reals; });
        var usedIds = similar.map(function (p) { return p.id; });

        var latest = others
            .filter(function (p) { return usedIds.indexOf(p.id) === -1; })
            .sort(function (a, b) { return new Date(b.date) - new Date(a.date); })
            .slice(0, LATEST_COUNT);

        fillGrid(section, "similar", similar);
        fillGrid(section, "latest", latest);
        return true;
    }

    function fillGrid(section, key, list) {
        var block = section.querySelector('[data-related-block="' + key + '"]');
        var grid = section.querySelector('[data-related-grid="' + key + '"]');
        if (!grid) return;
        if (!list.length) {
            if (block) block.style.display = "none";
            return;
        }
        
        grid.innerHTML = list.map(renderCard).join("");
    }

    function renderCard(p) {
        return "" +
            '<a href="' + p.url + '" class="RelatedCard">' +
                '<div class="RelatedImage">' +
                    '<img src="' + p.image + '" alt="' + p.imageAlt + '">' +
                    '<div class="RelatedOverlay"><span>' + p.label + "</span></div>" +
                "</div>" +
                '<div class="RelatedMeta">' +
                    '<p class="RelatedCategory">' + p.category + "</p>" +
                    '<h3 class="RelatedName">' + p.name + "</h3>" +
                "</div>" +
            "</a>";
    }

    function similarityScore(a, b) {
        var score = a.category === b.category ? 2 : 0;
        for (var i = 0; i < b.tags.length; i++) {
            if (a.tags.indexOf(b.tags[i]) !== -1) score++;
        }

        return score;
    }

    function findProject(id) {
        for (var i = 0; i < REALS.length; i++) {
            if (REALS[i].id === id) return REALS[i];
        }

        return null;
    }

    function getCurrentProjectId() {
        var canonical = document.querySelector('link[rel="canonical"]');
        var href = canonical ? canonical.getAttribute("href") : window.location.pathname;
        var match = href.match(/\/reals\/([^\/]+)\/?/);
        return match ? match[1] : null;
    }

    function tryInit() {
        if (filled) return true;
        var section = document.querySelector("[data-related-reals]");
        if (!section) return false;
        filled = fillRelated(section);
        return filled;
    }

    document.addEventListener("DOMContentLoaded", function () {
        if (tryInit()) return;

        var observer = new MutationObserver(function () {
            if (tryInit()) observer.disconnect();
        });

        observer.observe(document.body, { childList: true, subtree: true });
        setTimeout(function () { observer.disconnect(); }, 10000);
    });
})();

document.addEventListener("DOMContentLoaded", function () {
    var track = document.querySelector("[data-marquee-track]");
    if (!track) return;

    var showcase = REALS
        .filter(function (p) { return !p.comingSoon; })
        .slice()
        .sort(function (a, b) { return new Date(b.date) - new Date(a.date); });

    track.innerHTML = showcase.map(renderShowcaseCard).join("") +
                       showcase.map(renderShowcaseCardDuplicate).join("");

    function getShowcaseImage(p) {
        return p.heroImage;
    }

    function renderShowcaseCard(p) {
        return "" +
            '<a class="ProjectCard" href="' + p.url + '">' +
                '<div class="Preview">' +
                    '<img src="' + getShowcaseImage(p) + '" alt="' + p.imageAlt + '" loading="lazy">' +
                "</div>" +
                '<div class="Caption">' +
                    '<span class="ProjectName">' + p.label + "</span>" +
                    '<span class="ProjectDate">' + formatShowcaseDate(p.date) + "</span>" +
                "</div>" +
            "</a>";
    }

    function renderShowcaseCardDuplicate(p) {
        return "" +
            '<a class="ProjectCard" href="' + p.url + '" aria-hidden="true" tabindex="-1">' +
                '<div class="Preview">' +
                    '<img src="' + getShowcaseImage(p) + '" alt="" loading="lazy">' +
                "</div>" +
                '<div class="Caption">' +
                    '<span class="ProjectName">' + p.label + "</span>" +
                    '<span class="ProjectDate">' + formatShowcaseDate(p.date) + "</span>" +
                "</div>" +
            "</a>";
    }

    function formatShowcaseDate(iso) {
        var months = ["Janvier", "Février", "Mars", "Avril", "Mai", "Juin", "Juillet", "Août", "Septembre", "Octobre", "Novembre", "Décembre"];
        var parts = iso.split("-");
        return months[parseInt(parts[1], 10) - 1] + " " + parts[0];
    }
});